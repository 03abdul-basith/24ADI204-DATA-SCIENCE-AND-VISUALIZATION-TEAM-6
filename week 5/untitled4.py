import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.preprocessing import StandardScaler

# Load the dataset
df = pd.read_csv('/content/cleaned_diabetes_data.csv')
display(df.head())
display(df.info())

# Identify numerical and categorical columns
num_cols = df.select_dtypes(include=[np.number]).columns.tolist()
cat_cols = df.select_dtypes(exclude=[np.number]).columns.tolist()

print("Numerical columns identified:", num_cols)
print("Categorical columns identified:", cat_cols)

# Compute skewness
skew_vals = df[num_cols].skew()
print("\nSkewness values before transformation:\n", skew_vals)

# Fix skewness by applying log1p transformation to columns with highly skewed distributions
for col in num_cols:
    if abs(skew_vals[col]) > 0.75:
        if (df[col] >= 0).all():
            df[col] = np.log1p(df[col])
            print(f"Applied log1p transformation to: {col}")

# Scale numerical features
scaler = StandardScaler()
df[num_cols] = scaler.fit_transform(df[num_cols])

display(df[num_cols].head())

if cat_cols:
    df = pd.get_dummies(df, columns=cat_cols, drop_first=True)
    print("Categorical variables encoded.")
else:
    print("No categorical columns to encode.")

display(df.head())